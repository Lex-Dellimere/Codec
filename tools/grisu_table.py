"""Writes src/json/pow10.mettle: the cached powers of ten Grisu2 needs.

Entry i is 10^(-348 + 8*i) as a 64-bit mantissa f (top bit set, rounded to
nearest) and a binary exponent e, so the value is f * 2^e. Exact integer
arithmetic, so the table has no rounding error beyond the final rounding.

    python3 tools/grisu_table.py
"""
from fractions import Fraction

def entry(k):
    v = Fraction(10) ** k
    e = 0
    # Scale v into [2^63, 2^64).
    while v >= 2 ** 64:
        v /= 2
        e += 1
    while v < 2 ** 63:
        v *= 2
        e -= 1
    f = int(v)
    if v - f >= Fraction(1, 2):
        f += 1
    if f == 2 ** 64:
        f //= 2
        e += 1
    return f, e

fs, es = [], []
for i in range(87):
    f, e = entry(-348 + 8 * i)
    fs.append("0x%016x" % f)
    es.append(str(e))

out = ["// Generated by tools/grisu_table.py. Do not edit.",
       "// Entry i is 10^(-348 + 8*i) = CODEC_POW10_F[i] * 2^CODEC_POW10_E[i].",
       "",
       "export const CODEC_POW10_F: uint64[87] = ["]
for i in range(0, 87, 4):
    out.append("  " + ", ".join(fs[i:i + 4]) + ",")
out[-1] = out[-1].rstrip(",")
out.append("];")
out.append("")
out.append("export const CODEC_POW10_E: int32[87] = [")
for i in range(0, 87, 12):
    out.append("  " + ", ".join(es[i:i + 12]) + ",")
out[-1] = out[-1].rstrip(",")
out.append("];")
open("src/json/pow10.mettle", "w").write("\n".join(out) + "\n")
